CREATE TABLE IF NOT EXISTS visits (t INTEGER NOT NULL, name TEXT NOT NULL, line TEXT NOT NULL, c INTEGER NOT NULL, a REAL NOT NULL, b REAL NOT NULL, x REAL NOT NULL, tp REAL, hu REAL, pr REAL, created INTEGER NOT NULL, PRIMARY KEY (t, name, line));
CREATE INDEX IF NOT EXISTS visits_name ON visits(name, line);
CREATE INDEX IF NOT EXISTS visits_t ON visits(t);
